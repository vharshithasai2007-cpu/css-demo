import { useQuery } from '@tanstack/react-query'
import { Link } from 'react-router-dom'
import portalApi, {
  type PortalCategory,
  type PortalMeta,
  type PortalRequestType,
} from '../api'
import DataTable, { type DataTableColumn } from '../components/DataTable'
import InfoPanel from '../components/InfoPanel'
import PageHeading from '../components/PageHeading'

const requestTypeColumns: DataTableColumn<PortalRequestType>[] = [
  {
    key: 'label',
    header: 'Request type',
    render: (requestType) => requestType.label,
  },
  {
    key: 'description',
    header: 'Description',
    render: (requestType) => requestType.description,
  },
  {
    key: 'category',
    header: 'Subject category',
    render: (requestType) =>
      requestType.requires_category ? 'Required' : 'Not required',
  },
]

const categoryColumns: DataTableColumn<PortalCategory>[] = [
  {
    key: 'label',
    header: 'Subject category',
    render: (category) => category.label,
  },
  {
    key: 'description',
    header: 'Description',
    render: (category) => category.description,
  },
  {
    key: 'department',
    header: 'Simulated department',
    render: (category) => category.department,
  },
]

export default function Home() {
  const metaQuery = useQuery({
    queryKey: ['portal', 'meta'],
    queryFn: async () => {
      const response = await portalApi.get<PortalMeta>('/portal/meta')
      return response.data
    },
  })

  const requestTypes = metaQuery.data?.request_types ?? []
  const categories = metaQuery.data?.categories ?? []

  return (
    <>
      <PageHeading
        title="Centralized Support System"
        description="An unofficial educational replica of the AICTE student and institution support service."
      />

      <InfoPanel title="About this demonstration">
        <p>
          This is an unofficial educational replica of the AICTE Centralized Support
          System, built to demonstrate how a support request moves through a simulated
          workflow.
        </p>
        <p>
          It is not connected to the live AICTE portal, and no submission reaches AICTE
          or any institution.
        </p>
        <p>
          Replies and status changes are generated by a simulator after a short delay,
          so the full request lifecycle can be observed without contacting a real office.
        </p>
      </InfoPanel>

      {metaQuery.isError ? (
        <p className="portal-error-text">
          Portal information could not be loaded. The demonstration backend may not be
          running.
        </p>
      ) : null}

      <section className="portal-section" aria-labelledby="request-types-heading">
        <h2 className="portal-section-title" id="request-types-heading">
          Request types
        </h2>
        <p className="portal-section-intro">
          Request types describe why a stakeholder is contacting the Centralized Support
          System. They are separate from the technical subject categories below.
        </p>
        <DataTable
          columns={requestTypeColumns}
          rows={requestTypes}
          getRowKey={(requestType) => requestType.value}
          emptyMessage={
            metaQuery.isLoading ? 'Loading request types…' : 'No request types available.'
          }
        />
      </section>

      <section className="portal-section" aria-labelledby="subject-categories-heading">
        <h2 className="portal-section-title" id="subject-categories-heading">
          Subject categories
        </h2>
        <p className="portal-section-intro">
          The seven subject categories are used when a request is submitted as a
          complaint or a grievance. Each category is routed to a simulated department.
        </p>
        <DataTable
          columns={categoryColumns}
          rows={categories}
          getRowKey={(category) => category.value}
          emptyMessage={
            metaQuery.isLoading ? 'Loading subject categories…' : 'No subject categories available.'
          }
        />
      </section>

      <section className="portal-section" aria-labelledby="process-heading">
        <h2 className="portal-section-title" id="process-heading">
          How a request is processed (simulated)
        </h2>
        <ol className="portal-steps">
          <li>Register or sign in with a demonstration account.</li>
          <li>
            Submit a request and receive a simulated reference ID beginning with CSSD.
          </li>
          <li>
            The simulator moves the request through review and generates a department
            reply.
          </li>
          <li>
            The request is marked resolved. You can follow every status change by
            reference ID.
          </li>
        </ol>
      </section>

      <p className="portal-home-links">
        <Link to="/css-demo/register">Register</Link>
        <Link to="/css-demo/login">Login</Link>
      </p>
    </>
  )
}
